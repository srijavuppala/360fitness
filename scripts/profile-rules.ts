// Generate the mobile profile rule schema from the same questions used by onboarding.
// Run through apps/mobile's tsx; --check exits nonzero when the committed rules drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { profileSteps, choicesFor, MAINTAIN_TOLERANCE_KG } from '../apps/mobile/src/domain/profile';
const file = new URL('../firestore.rules', import.meta.url);
const start = '    // BEGIN MOBILE PROFILE SCHEMA';
const end = '    // END MOBILE PROFILE SCHEMA';
const questions = profileSteps.flatMap(step => step.questions);
const quote = (value: unknown) => JSON.stringify(value);
const checks = questions.map(q => {
  const ref = `a.${q.key}`;
  const choices = choicesFor(q.key);
  let check = choices.length ? q.kind === 'multi'
    ? `(${ref} is list && ${ref}.size() > 0 && ${ref}.size() == ${ref}.toSet().size() && ${ref}.hasOnly(${quote(choices)}) && (${ref}.size() == 1 || !${ref}.hasAny(['None known', 'Not sure', 'No preference yet', 'None'])))`
    : `${ref} in ${quote(choices)}`
    : `(${ref} is string && ${ref}.size() > 0 && ${ref}.size() <= ${q.maxLength ?? 300})`;
  if (q.kind === 'time') check = `(${ref} is string && ${ref}.matches('^([01][0-9]|2[0-3]):[0-5][0-9]$'))`;
  if (q.kind === 'number') check = `(${ref} is string && ${ref}.size() <= 300 && ${ref}.matches('^[0-9]+(\\\\.[0-9]{1,2})?$') && float(${ref}) >= ${q.min ?? 0} && float(${ref}) <= ${q.max ?? 100000})`;
  if (q.key === 'weeklyPace') return `((math.abs(float(a.targetWeightKg) - float(a.currentWeightKg)) > ${MAINTAIN_TOLERANCE_KG}) ? ${check} : !('weeklyPace' in a))`;
  if (q.when) {
    const condition = q.when.key === 'allergies' ? `${quote(q.when.value)} in a.allergies` : `a.${q.when.key} == ${quote(q.when.value)}`;
    return `((${condition}) ? ${check} : !(${quote(q.key)} in a))`;
  }
  return q.required ? check : `(!(${quote(q.key)} in a) || ${check})`;
});
const generated = `${start}
    // Generated by scripts/profile-rules.ts. Legacy /users rules do not cover this collection.
    function validMobileAnswers(a) {
      return a is map && a.keys().hasOnly(${quote(questions.map(q => q.key))})
        && ${checks.join('\n        && ')};
    }
    function validMobileProfile() {
      let d = request.resource.data;
      return d.keys().hasAll(['schemaVersion', 'revision', 'generation', 'profile', 'updatedAt'])
        && d.keys().hasOnly(['schemaVersion', 'revision', 'generation', 'profile', 'updatedAt'])
        && d.schemaVersion == 1 && d.revision is int && d.revision > 0
        && d.generation is string && d.generation.matches('^[A-Za-z0-9]{20}$')
        && d.updatedAt == request.time
        && d.profile is map && d.profile.keys().hasOnly(['version', 'answers', 'updatedAt'])
        && d.profile.version == 2 && d.profile.updatedAt is string && d.profile.updatedAt.size() <= 40
        && validMobileAnswers(d.profile.answers);
    }
    match /mobileProfiles/{uid} {
      allow read, delete: if isOwner(uid) && request.auth.token.email_verified == true;
      allow create: if isOwner(uid) && request.auth.token.email_verified == true
        && validMobileProfile() && request.resource.data.revision == 1;
      allow update: if isOwner(uid) && request.auth.token.email_verified == true
        && validMobileProfile() && request.resource.data.revision == resource.data.revision + 1
        && request.resource.data.generation == resource.data.generation;
    }
${end}`;
const existing = readFileSync(file, 'utf8');
const next = existing.includes(start)
  ? existing.slice(0, existing.indexOf(start)) + generated + existing.slice(existing.indexOf(end) + end.length)
  : existing.replace('    // Anything not matched above', () => generated + '\n\n    // Anything not matched above');
if (process.argv.includes('--check')) {
  if (existing !== next) throw new Error('Mobile profile rules are out of date. Run npm run rules:generate in apps/mobile.');
} else writeFileSync(file, next);
